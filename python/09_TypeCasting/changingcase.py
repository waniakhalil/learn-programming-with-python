# Function of String for Changing Casting
print("Function of String for Changing Casting:")
name="Pakistan"
print(name)
print("1.Upper Function of String:")
print(name.upper())
print("2.Lower Function of String:")
print(name.lower())
print("3.Title Function of String:")
print(name.title())



#Output:
##Function of String for Changing Casting:
#Pakistan
#1.Upper Function of String:
#PAKISTAN
#2.Lower Function of String:
#pakistan
#3.Title Function of String:
#'Pakistan'